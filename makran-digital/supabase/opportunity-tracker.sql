-- Makran Digital: private opportunity application tracker
-- Run this script once in Supabase Dashboard > SQL Editor.
create table if not exists public.opportunity_saves (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  opportunity_id text not null,
  title text not null,
  category text not null default 'other',
  location text,
  url text,
  application_status text not null default 'Interested'
    check (application_status in ('Interested','Preparing documents','Applied','Under review','Interview','Accepted','Rejected','Withdrawn')),
  deadline date,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, opportunity_id)
);
alter table public.opportunity_saves enable row level security;
drop policy if exists "Users can view their own saved opportunities" on public.opportunity_saves;
create policy "Users can view their own saved opportunities"
  on public.opportunity_saves for select to authenticated
  using (auth.uid() = user_id);
drop policy if exists "Users can save their own opportunities" on public.opportunity_saves;
create policy "Users can save their own opportunities"
  on public.opportunity_saves for insert to authenticated
  with check (auth.uid() = user_id);
drop policy if exists "Users can update their own saved opportunities" on public.opportunity_saves;
create policy "Users can update their own saved opportunities"
  on public.opportunity_saves for update to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);
drop policy if exists "Users can remove their own saved opportunities" on public.opportunity_saves;
create policy "Users can remove their own saved opportunities"
  on public.opportunity_saves for delete to authenticated
  using (auth.uid() = user_id);
create index if not exists opportunity_saves_user_created_idx
  on public.opportunity_saves (user_id, created_at desc);
